"""Export a board as a project pack: files + CREDITS.txt + assets.json.

Drop the zip into your editing project and the credits you owe are already
written down (and reference-only items are clearly flagged).
"""

from __future__ import annotations

import json
import re
import zipfile
from pathlib import Path
from typing import Any

from .context import Context
from .models import Usage
from .storage import guess_ext

USAGE_TITLES = {
    Usage.FREE: "Free to use (no credit required — crediting is still nice)",
    Usage.OWN: "Your own assets",
    Usage.CREDIT: "Credit REQUIRED (put these in your description/credits)",
    Usage.NONCOMMERCIAL: "NON-COMMERCIAL only",
    Usage.CHECK: "CHECK the license on the source page before publishing",
    Usage.REFERENCE: "REFERENCE ONLY — do not publish these; use them for inspiration",
}


def _slug(text: str, n: int = 50) -> str:
    s = re.sub(r"[^a-zA-Z0-9]+", "-", text or "").strip("-").lower()
    return s[:n] or "asset"


def export_board(ctx: Context, board_id: int, out_path: Path) -> dict[str, Any]:
    board = ctx.db.get_board(board_id)
    if not board:
        raise ValueError("board not found")
    ids = ctx.db.board_item_ids(board_id)
    assets = ctx.db.get_assets(ids)
    grouped: dict[str, list[dict[str, Any]]] = {}
    missing = 0
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(out_path, "w", zipfile.ZIP_DEFLATED) as zf:
        meta = []
        for i, aid in enumerate(ids, 1):
            a = assets.get(aid)
            if not a:
                continue
            grouped.setdefault(a.get("usage") or Usage.CHECK, []).append(a)
            entry = {k: a.get(k) for k in ("id", "kind", "title", "author", "page_url", "license_label", "license_url",
                                          "usage", "attribution", "tags")}
            key = a.get("blob_key")
            if key:
                ext = Path(key).suffix or guess_ext(a.get("blob_mime"), "")
                name = f"files/{i:03d}_{a.get('usage')}_{_slug(a.get('title') or aid)}{ext}"
                local = ctx.storage.local_path(key)
                try:
                    if local is not None:
                        zf.write(local, name)
                    else:
                        with ctx.storage.open(key) as fh:
                            zf.writestr(name, fh.read())
                    entry["file"] = name
                except OSError:
                    missing += 1
            else:
                missing += 1
            meta.append(entry)
        lines = [f"CREDITS — board: {board['name']}", "=" * 60, ""]
        for usage in (Usage.CREDIT, Usage.NONCOMMERCIAL, Usage.CHECK, Usage.REFERENCE, Usage.FREE, Usage.OWN):
            items = grouped.get(usage)
            if not items:
                continue
            lines.append(f"## {USAGE_TITLES.get(usage, usage)}")
            for a in items:
                lines.append(f"- {a.get('attribution') or a.get('title')}")
            lines.append("")
        lines.append("Generated by NOZE. Licenses were read from each source's API — always double-check before publishing.")
        zf.writestr("CREDITS.txt", "\n".join(lines))
        zf.writestr("assets.json", json.dumps(meta, indent=2, ensure_ascii=False))
    return {"path": str(out_path), "items": len(ids), "without_file": missing}
