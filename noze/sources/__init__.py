"""Registry of every source connector.

Adding a source = one class with `search()` returning normalized Assets, then
list it here. See docs/SOURCES.md.
"""

from __future__ import annotations

from ..config import Settings
from ..http import Http
from .ambientcg import AmbientCG
from .arena import Arena
from .base import DownloadPart, SearchResult, Source
from .civitai import Civitai
from .fontsource import Fontsource
from .github import GitHub
from .iconify import Iconify
from .internet_archive import InternetArchive
from .lottiefiles import LottieFiles
from .media import Freesound, Giphy, Reddit
from .museums import ArtInstituteChicago, ClevelandMuseum, Europeana, MetMuseum, Smithsonian
from .nasa import NASA
from .openverse import Openverse
from .polyhaven import PolyHaven
from .stock import Pexels, Pixabay, Unsplash
from .wikimedia import Wikimedia

SOURCE_CLASSES: list[type[Source]] = [
    # keyless, on by default
    Openverse, Wikimedia, PolyHaven, AmbientCG, NASA, MetMuseum, ArtInstituteChicago, ClevelandMuseum,
    Smithsonian, Europeana, InternetArchive, Iconify, Fontsource, GitHub, Arena, LottieFiles, Civitai,
    # free API key required
    Pexels, Pixabay, Unsplash, Freesound, Giphy, Reddit,
]

# Assets that did not come from a search source
LOCAL_SOURCES = {
    "upload": "Upload",
    "folder": "Local folder",
    "web": "Saved from web",
    "pinterest": "Pinterest (your pins)",
    "generated": "Generated by you",
}


def build_sources(settings: Settings, http: Http) -> dict[str, Source]:
    return {cls.name: cls(settings, http) for cls in SOURCE_CLASSES}


def source_labels() -> dict[str, str]:
    labels = {cls.name: cls.label for cls in SOURCE_CLASSES}
    labels.update(LOCAL_SOURCES)
    return labels


__all__ = ["Source", "SearchResult", "DownloadPart", "SOURCE_CLASSES", "LOCAL_SOURCES", "build_sources", "source_labels"]
