"""Optional: generate missing assets with AI (Seedance for video, FLUX for
images, or any Replicate model) and bank the result as your own asset.

Needs REPLICATE_API_TOKEN. Every generation costs Replicate credits.
"""

from __future__ import annotations

import asyncio
import hashlib
import time
from typing import Any

from .context import Context
from .http import Http, SourceError
from .licenses import LicenseInfo
from .models import Asset, Kind, Usage
from .storage import guess_ext

API = "https://api.replicate.com/v1"


def _first_url(output: Any) -> str | None:
    if isinstance(output, str) and output.startswith("http"):
        return output
    if isinstance(output, list):
        for o in output:
            u = _first_url(o)
            if u:
                return u
    if isinstance(output, dict):
        for key in ("video", "image", "url", "output"):
            u = _first_url(output.get(key))
            if u:
                return u
    return None


async def generate(ctx: Context, http: Http, prompt: str, kind: str = "image", model: str | None = None,
                   extra_input: dict[str, Any] | None = None, timeout_s: float = 900) -> dict[str, Any]:
    token = ctx.settings.key("REPLICATE_API_TOKEN")
    if not token:
        raise SourceError("set REPLICATE_API_TOKEN to generate with AI")
    kind = Kind.VIDEO if kind == "video" else Kind.IMAGE
    model = model or (ctx.settings.gen_video_model if kind == Kind.VIDEO else ctx.settings.gen_image_model)
    if model.count("/") != 1:
        raise SourceError("model must look like owner/name, e.g. bytedance/seedance-1-lite")
    headers = {"Authorization": f"Bearer {token}", "Prefer": "wait=60"}
    body = {"input": {"prompt": prompt, **(extra_input or {})}}
    pred = await http.post_json(f"{API}/models/{model}/predictions", body, headers=headers, timeout=90)
    started = time.time()
    while pred.get("status") not in ("succeeded", "failed", "canceled"):
        if time.time() - started > timeout_s:
            raise SourceError("generation timed out")
        await asyncio.sleep(4)
        get_url = (pred.get("urls") or {}).get("get") or f"{API}/predictions/{pred.get('id')}"
        pred = await http.get_json(get_url, headers={"Authorization": f"Bearer {token}"})
    if pred.get("status") != "succeeded":
        raise SourceError(f"generation {pred.get('status')}: {str(pred.get('error'))[:200]}")
    url = _first_url(pred.get("output"))
    if not url:
        raise SourceError("model returned no file")
    d = await http.download(url, ctx.settings.tmp_dir, ctx.settings.max_download_mb * 1024 * 1024)
    mime = (d.mime or "").split(";")[0]
    try:
        key = ctx.storage.put_file(d.path, d.sha256, guess_ext(mime, url), mime)
    finally:
        d.path.unlink(missing_ok=True)
    if mime.startswith("video/"):
        kind = Kind.VIDEO
    lic = LicenseInfo("own", f"Generated by you with {model} — check the model's terms for commercial use", Usage.OWN)
    gid = hashlib.sha1(f"{model}:{prompt}:{pred.get('id')}".encode()).hexdigest()[:16]
    asset = Asset(source="generated", source_id=gid, kind=kind, title=prompt[:90], description=prompt,
                  tags=["ai-generated", model.split("/")[-1]], author="you", page_url="",
                  license=lic.code, license_label=lic.label, usage=lic.usage,
                  extra={"prompt": prompt, "model": model, "prediction": pred.get("id")})
    ctx.db.upsert_assets([asset])
    # thumbnail is made from the stored file by the enrichment worker
    ctx.db.update_asset(asset.id, blob_key=key, blob_size=d.size, blob_mime=mime,
                        preview_url=f"/api/assets/{asset.id}/file", thumb_state=0)
    return ctx.db.get_asset(asset.id)
